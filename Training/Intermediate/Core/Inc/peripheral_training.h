#ifndef PERIPHERAL_TRAINING_H
#define PERIPHERAL_TRAINING_H

#include "main.h"
#include <stdint.h>

/* -------------------------------------------------------------------------- */
/*  Training selector: change ACTIVE_TRAINING, rebuild, flash.                */
/*  (or build with -DACTIVE_TRAINING=TRAINING_xxx)                            */
/* -------------------------------------------------------------------------- */
typedef enum
{
    TRAINING_NONE = 0,

    /* GPIO */
    TRAINING_GPIO_LED,           /* SetLed on/off, ToggleLed                  */
    TRAINING_GPIO_SWITCH,        /* LED follows the BOOT1 switch              */

    /* UART */
    TRAINING_UART_PRINT,         /* HAL_UART_Transmit                         */
    TRAINING_UART_RECEIVE,       /* HAL_UART_Receive, fixed number of bytes   */
    TRAINING_UART_LED_TOGGLE,     /* send LED_TOGGLE\r\n from a terminal      */

    /* SPI + MCP23S17 expander */
    TRAINING_SPI_EXPANDER,       /* init + read back direction registers      */
    TRAINING_SPI_LEDS,           /* binary counter on GPA0..GPA3              */
    TRAINING_SPI_PORTS,          /* read ports A and B                        */
    
    /* I2C + MC3479 IMU */
    TRAINING_I2C_PROBE,          /* DeviceReady, chip ID, wrong-address test  */
    TRAINING_I2C_ACCEL          /* read X/Y/Z                                */

} Training_t;

#ifndef ACTIVE_TRAINING
#define ACTIVE_TRAINING   TRAINING_GPIO_LED
#endif

/* Call Peripheral_Training_Init() once after the MX_xxx_Init() calls,
 * then Peripheral_Training_Run() repeatedly inside while(1). */
void Peripheral_Training_Init(void);
void Peripheral_Training_Run(void);


/*
 * Update these to match the names generated by CubeMX and the schematic.
 * Keep HAL initialization in main before calling these training functions.
 */
extern I2C_HandleTypeDef hi2c1;
extern SPI_HandleTypeDef hspi2;      /* NOTE: this project uses SPI2 */
extern UART_HandleTypeDef huart1;

#ifndef TRAINING_I2C_HANDLE
#define TRAINING_I2C_HANDLE hi2c1
#endif
#ifndef TRAINING_SPI_HANDLE
#define TRAINING_SPI_HANDLE hspi2
#endif
#ifndef TRAINING_UART_HANDLE
#define TRAINING_UART_HANDLE huart1
#endif

/* MC3479 7-bit I2C address is 0x4C. (HAL wants it shifted left by one.) */
#ifndef MC3479_I2C_ADDR_7BIT
#define MC3479_I2C_ADDR_7BIT 0x4C
#endif
#define MC3479_I2C_ADDR_HAL ((uint16_t)(MC3479_I2C_ADDR_7BIT << 1))

/* Generated GPIO symbols expected for the schematic net Z_SPI_nCS. */
#ifndef MCP23S17_CS_GPIO_Port
#define MCP23S17_CS_GPIO_Port Z_SPI_nCS_GPIO_Port
#endif
#ifndef MCP23S17_CS_Pin
#define MCP23S17_CS_Pin Z_SPI_nCS_Pin
#endif

/* GPIO training: PC13 LED and PB8 / board label BOOT1. */
void GPIO_Training_SetLed(uint8_t on);
void GPIO_Training_ToggleLed(void);
GPIO_PinState GPIO_Training_ReadBoot1(void);     /* reads BOOT1, also sets the LED to match */

/* I2C training and MC3479 sensor. */
HAL_StatusTypeDef I2C_Training_DeviceReady(uint16_t device_address);
HAL_StatusTypeDef I2C_Training_WriteRegister(uint16_t device_address,
                                              uint8_t register_address,
                                              uint8_t value);
HAL_StatusTypeDef I2C_Training_ReadRegister(uint16_t device_address,
                                             uint8_t register_address,
                                             uint8_t *data);
HAL_StatusTypeDef I2C_Training_ReadBytes(uint16_t device_address,
                                          uint8_t start_register,
                                          uint8_t *buffer,
                                          uint16_t length);
HAL_StatusTypeDef I2C_Training_InitIMU(void);
HAL_StatusTypeDef I2C_Training_ReadAcceleration(int16_t xyz[3]);
HAL_StatusTypeDef I2C_Training_ReadAccelerationMg(int32_t xyz_mg[3]);

/* SPI training and MCP23S17 expander. */
HAL_StatusTypeDef SPI_Training_InitExpander(void);
HAL_StatusTypeDef SPI_Training_ReadRegister(uint8_t reg, uint8_t *value);
HAL_StatusTypeDef SPI_Training_WriteRegister(uint8_t reg, uint8_t value);
HAL_StatusTypeDef SPI_Training_SetLeds(uint8_t led_mask);
HAL_StatusTypeDef SPI_Training_ReadPorts(uint16_t *value);

/* UART training. */
HAL_StatusTypeDef UART_Training_Print(const char *message);
HAL_StatusTypeDef UART_Training_TransmitBytes(const uint8_t *data, uint16_t length);
HAL_StatusTypeDef UART_Training_ReceiveBytes(uint8_t *buffer,
                                              uint16_t length,
                                              uint32_t timeout_ms);
HAL_StatusTypeDef UART_Training_WaitForToggle(uint32_t timeout_ms);

#endif
