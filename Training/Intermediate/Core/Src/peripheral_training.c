#include "peripheral_training.h"
#include <string.h>

/*
 * Training selector.
 *
 * In main.c:
 *     USER CODE BEGIN Includes -> #include "peripheral_training.h"
 *     USER CODE BEGIN 2        -> Peripheral_Training_Init();
 *     USER CODE BEGIN 3        -> Peripheral_Training_Run();      (inside while(1))
 *
 * Choose the training with ACTIVE_TRAINING in peripheral_training.h.
 *
 * The runners below call the functions the students complete in
 * gpio_/i2c_/spi_/uart_training.c and put the results in "g_" variables.
 * Add them to Live Expressions in the debugger.
 * Students normally do not edit this file.
 */

/* Results (watch these in the debugger) */
volatile HAL_StatusTypeDef g_status         = HAL_ERROR;   /* status of the latest operation  */
volatile HAL_StatusTypeDef g_init_status    = HAL_ERROR;   /* IMU / expander init result      */
volatile HAL_StatusTypeDef g_wrong_addr     = HAL_OK;      /* I2C wrong-address test          */
volatile HAL_StatusTypeDef g_command_status = HAL_ERROR;   /* UART LED_TOGGLE result          */
volatile uint8_t           g_chip_id        = 0;
volatile int16_t           g_accel_raw[3]   = {0};
volatile int32_t           g_accel_mg[3]    = {0};
volatile uint8_t           g_iodira         = 0;
volatile uint8_t           g_iodirb         = 0;
volatile uint16_t          g_ports          = 0;
volatile GPIO_PinState     g_switch         = GPIO_PIN_RESET;
volatile uint8_t           g_rx_buffer[4]   = {0};


void Peripheral_Training_Init(void)
{
    switch (ACTIVE_TRAINING)
    {
    case TRAINING_I2C_PROBE:
    case TRAINING_I2C_ACCEL:
        g_init_status = I2C_Training_InitIMU();
        break;

    case TRAINING_SPI_EXPANDER:
    case TRAINING_SPI_LEDS:
    case TRAINING_SPI_PORTS:
        g_init_status = SPI_Training_InitExpander();
        break;

    default:
        break;
    }
}


/* ---------------------------- GPIO runners ------------------------------- */

static void Run_GpioLed(void)
{
    GPIO_Training_SetLed(1);
    HAL_Delay(500);
    GPIO_Training_SetLed(0);
    HAL_Delay(500);
    GPIO_Training_ToggleLed();
    HAL_Delay(500);
    GPIO_Training_ToggleLed();
    HAL_Delay(500);
}

static void Run_GpioSwitch(void)
{
    /* ReadBoot1() reads the switch and also sets the LED to match. */
    g_switch = GPIO_Training_ReadBoot1();

    HAL_Delay(10);
}


/* ----------------------------- I2C runners ------------------------------- */

static void Run_I2cProbe(void)
{
    g_status     = I2C_Training_DeviceReady(MC3479_I2C_ADDR_HAL);
    g_wrong_addr = I2C_Training_DeviceReady(MC3479_I2C_ADDR_7BIT);   /* UNSHIFTED on purpose */

    if (g_status == HAL_OK)
    {
        uint8_t id = 0;
        if (I2C_Training_ReadRegister(MC3479_I2C_ADDR_HAL, 0x18, &id) == HAL_OK)
        {
            g_chip_id = id;
        }
    }

    __NOP();   /* breakpoint here */
    HAL_Delay(500);
}

static void Run_I2cAccel(void)
{
    int16_t raw[3] = {0};
    int32_t mg[3]  = {0};

    g_status = I2C_Training_ReadAcceleration(raw);
    if (g_status == HAL_OK)
    {
        g_accel_raw[0] = raw[0];
        g_accel_raw[1] = raw[1];
        g_accel_raw[2] = raw[2];
    }

    if (I2C_Training_ReadAccelerationMg(mg) == HAL_OK)
    {
        g_accel_mg[0] = mg[0];
        g_accel_mg[1] = mg[1];
        g_accel_mg[2] = mg[2];
    }

    __NOP();   /* breakpoint here */
    HAL_Delay(100);
}


/* ----------------------------- SPI runners ------------------------------- */

static void Run_SpiExpander(void)
{
    uint8_t value = 0;

    if (SPI_Training_ReadRegister(0x00, &value) == HAL_OK) { g_iodira = value; }   /* IODIRA */
    if (SPI_Training_ReadRegister(0x01, &value) == HAL_OK) { g_iodirb = value; }   /* IODIRB */

    __NOP();   /* breakpoint here: expect IODIRA = 0xF0, IODIRB = 0xFF after init */
    HAL_Delay(500);
}

static void Run_SpiLeds(void)
{
    static uint8_t counter = 0;

    g_status = SPI_Training_SetLeds(counter);
    counter = (counter + 1U) & 0x0FU;

    HAL_Delay(500);
}

static void Run_SpiPorts(void)
{
    uint16_t ports = 0;

    g_status = SPI_Training_ReadPorts(&ports);
    if (g_status == HAL_OK)
    {
        g_ports = ports;     /* port A in the high byte, port B in the low byte */
    }

    __NOP();   /* breakpoint here */
    HAL_Delay(200);
}


/* ----------------------------- UART runners ------------------------------ */

static void Run_UartPrint(void)
{
    static const uint8_t bytes[] = { 'B', 'Y', 'T', 'E', 'S', '\r', '\n' };

    g_status = UART_Training_Print("Hello from the solar car!\r\n");
    (void)UART_Training_TransmitBytes(bytes, sizeof(bytes));

    HAL_Delay(1000);
}

static void Run_UartReceive(void)
{
    uint8_t buffer[4] = {0};

    UART_Training_Print("Type 4 characters: ");
    g_status = UART_Training_ReceiveBytes(buffer, sizeof(buffer), 5000);

    if (g_status == HAL_OK)
    {
        memcpy((void *)g_rx_buffer, buffer, sizeof(buffer));
        UART_Training_Print("\r\nYou typed: ");
        UART_Training_TransmitBytes(buffer, sizeof(buffer));
        UART_Training_Print("\r\n");
    }
    else
    {
        UART_Training_Print("\r\n(timeout)\r\n");
    }
}

static void Run_UartLedToggle(void)
{
    UART_Training_Print("Send LED_TOGGLE + Enter: ");

    /* The student function only receives and checks the message... */
    g_command_status = UART_Training_WaitForToggle(10000);

    /* ...the toggle itself is handled here, in the test. */
    if (g_command_status == HAL_OK)
    {
        GPIO_Training_ToggleLed();
        UART_Training_Print("OK\r\n");
    }
    else
    {
        UART_Training_Print("(no valid command)\r\n");
    }
}


void Peripheral_Training_Run(void)
{
    switch (ACTIVE_TRAINING)
    {
    case TRAINING_GPIO_LED:        Run_GpioLed();        break;
    case TRAINING_GPIO_SWITCH:     Run_GpioSwitch();     break;

    case TRAINING_I2C_PROBE:       Run_I2cProbe();       break;
    case TRAINING_I2C_ACCEL:       Run_I2cAccel();       break;

    case TRAINING_SPI_EXPANDER:    Run_SpiExpander();    break;
    case TRAINING_SPI_LEDS:        Run_SpiLeds();        break;
    case TRAINING_SPI_PORTS:       Run_SpiPorts();       break;

    case TRAINING_UART_PRINT:      Run_UartPrint();      break;
    case TRAINING_UART_RECEIVE:    Run_UartReceive();    break;
    case TRAINING_UART_LED_TOGGLE: Run_UartLedToggle(); break;

    case TRAINING_NONE:
    default:
        HAL_Delay(100);
        break;
    }
}
